const { sendWithChannelButton } = require('../../lib/channelButton');
const settings = require('../../settings');

async function azkarCommand(sock, chatId, message, args) {
    const helpMsg = `📿 *الأذكار* 📿\n\n` +
        `1. 🌅 *أذكار الصباح*\n` +
        `2. 🌙 *أذكار المساء*\n` +
        `3. 😴 *أذكار النوم*\n` +
        `4. 🕋 *أذكار بعد الصلاة*\n\n` +
        `📝 *الاستخدام:* \n` +
        `.azkar 1 - أذكار الصباح\n` +
        `.azkar 2 - أذكار المساء\n` +
        `.azkar 3 - أذكار النوم\n` +
        `.azkar 4 - أذكار بعد الصلاة\n\n` +
        `⚔️ ${settings.botName}`;

    if (!args[0]) {
        return await sendWithChannelButton(sock, chatId, helpMsg, message);
    }

    const choice = args[0];
    let response = "";

    if (choice === '1') {
        response = `🌅 *أذكار الصباح*\n\n` +
            `▫️ أَصْبَحْنَا وَأَصْبَحَ الْمُلْكُ لِلَّهِ وَالْحَمْدُ لِلَّهِ لَا إِلَهَ إِلَّا اللهُ وَحْدَهُ لَا شَرِيكَ لَهُ...\n\n` +
            `▫️ اللّهُ لاَ إِلَـهَ إِلاَّ هُوَ الْحَيُّ الْقَيُّومُ لاَ تَأْخُذُهُ سِنَةٌ وَلاَ نَوْمٌ...\n\n` +
            `▫️ بِسْمِ اللَّهِ الَّذِي لَا يَضُرُّ مَعَ اسْمِهِ شَيْءٌ فِي الْأَرْضِ وَلَا فِي السَّمَاءِ وَهُوَ السَّمِيعُ الْعَلِيمُ (3 مرات)`;
    } else if (choice === '2') {
        response = `🌙 *أذكار المساء*\n\n` +
            `▫️ أَمْسَيْنَا وَأَمْسَى الْمُلْكُ لِلَّهِ وَالْحَمْدُ لِلَّهِ لَا إِلَهَ إِلَّا اللهُ وَحْدَهُ لَا شَرِيكَ لَهُ...\n\n` +
            `▫️ أَعُوذُ بِكَلِمَاتِ اللَّهِ التَّامَّاتِ مِنْ شَرِّ مَا خَلَقَ (3 مرات)\n\n` +
            `▫️ رَضِيتُ بِاللَّهِ رَبًّا، وَبِالْإِسْلَامِ دِينًا، وَبِمُحَمَّدٍ صَلَّى اللَّهُ عَلَيْهِ وَسَلَّمَ نَبِيًّا (3 مرات)`;
    } else if (choice === '3') {
        response = `😴 *أذكار النوم*\n\n` +
            `▫️ بِاسْمِكَ رَبِّي وَضَعْتُ جَنْبِي وَبِكَ أَرْفَعُهُ، إِنْ أَمْسَكْتَ نَفْسِي فَارْحَمْهَا، وَإِنْ أَرْسَلْتَهَا فَاحْفَظْهَا بِمَا تَحْفَظُ بِهِ عِبَادَكَ الصَّالِحِينَ.\n\n` +
            `▫️ اللّهُمَّ قِنِي عَذَابَكَ يَوْمَ تَبْعَثُ عِبَادَكَ (3 مرات).\n\n` +
            `▫️ بِاسْمِكَ اللّهُمَّ أَمُوتُ وَأَحْيَا.`;
    } else if (choice === '4') {
        response = `🕋 *أذكار بعد الصلاة*\n\n` +
            `▫️ أَسْتَغْفِرُ اللهَ (3 مَرَّاتٍ).\n\n` +
            `▫️ اللَّهُمَّ أَنْتَ السَّلَامُ وَمِنْكَ السَّلَامُ، تَبَارَكْتَ يَا ذَا الْجَلَالِ وَالْإِكْرَامِ.\n\n` +
            `▫️ لَا إِلَهَ إِلَّا اللهُ وَحْدَهُ لَا شَرِيكَ لَهُ، لَهُ الْمُلْكُ وَلَهُ الْحَمْدُ وَهُوَ عَلَى كُلِّ شَيْءٍ قَدِيرٌ.`;
    } else {
        return await sendWithChannelButton(sock, chatId, "❌ اختيار خاطئ. استخدم من 1 إلى 4.", message);
    }

    response += `\n\n⚔️ ${settings.botName}`;
    await sock.sendMessage(chatId, { text: response }, { quoted: message });
}

module.exports = azkarCommand;
